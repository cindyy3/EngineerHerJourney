// DOM elements
const tabTriggers = document.querySelectorAll('.tab-trigger');
const tabPanels = document.querySelectorAll('.tab-panel');

// Initialize the page
document.addEventListener('DOMContentLoaded', () => {
  // Populate all resource grids
  populateResourceGrid('scholarships');
  populateResourceGrid('opportunities');
  populateResourceGrid('learn');
  populateResourceGrid('diy');
  
  // Set up tab event listeners
  tabTriggers.forEach(trigger => {
    trigger.addEventListener('click', () => {
      const tabName = trigger.getAttribute('data-tab');
      switchTab(tabName);
    });
  });
});

function populateResourceGrid(category) {
  const grid = document.getElementById(`${category}-grid`);
  const resources = resourcesData[category];
  
  if (!grid || !resources) return;
  
  grid.innerHTML = '';
  
  resources.forEach((resource, index) => {
    const card = createResourceCard(resource, index);
    grid.appendChild(card);
  });
}

function createResourceCard(resource, index) {
  const card = document.createElement('div');
  card.className = 'resource-card';
  card.style.animationDelay = `${index * 0.1}s`;
  
  const sourceHtml = resource.source ? 
    `<p class="resource-source">Source: ${resource.source}</p>` : '';
  
  const gradeLevelsHtml = resource.gradeLevels ? 
    `<p class="resource-grade-levels">Grade Levels: ${resource.gradeLevels}</p>` : '';
  
  card.innerHTML = `
    <h3 class="resource-title">${resource.title}</h3>
    ${sourceHtml}
    <p class="resource-description">${resource.description}</p>
    ${gradeLevelsHtml}
    <a href="${resource.link}" target="_blank" rel="noopener noreferrer" class="resource-link">
      Learn More
      <script src="https://kit.fontawesome.com/f6311cd755.js" crossorigin="anonymous"></script>
      <i class="fa-solid fa-arrow-up-right-from-square"></i>
    </a>
  `;
  
  return card;
}

function switchTab(tabName) {
  // Update tab triggers
  tabTriggers.forEach(trigger => {
    trigger.classList.remove('active');
    if (trigger.getAttribute('data-tab') === tabName) {
      trigger.classList.add('active');
    }
  });
  
  // Update tab panels
  tabPanels.forEach(panel => {
    panel.classList.remove('active');
    if (panel.id === tabName) {
      panel.classList.add('active');
    }
  });
}

// Add smooth scrolling for any internal links
document.querySelectorAll('a[href^="#"]').forEach(anchor => {
  anchor.addEventListener('click', function (e) {
    e.preventDefault();
    const target = document.querySelector(this.getAttribute('href'));
    if (target) {
      target.scrollIntoView({
        behavior: 'smooth',
        block: 'start'
      });
    }
  });
});

// Add keyboard navigation for tabs
document.addEventListener('keydown', (e) => {
  if (e.target.classList.contains('tab-trigger')) {
    const triggers = Array.from(tabTriggers);
    const currentIndex = triggers.indexOf(e.target);
    
    let nextIndex;
    
    if (e.key === 'ArrowLeft') {
      e.preventDefault();
      nextIndex = currentIndex > 0 ? currentIndex - 1 : triggers.length - 1;
    } else if (e.key === 'ArrowRight') {
      e.preventDefault();
      nextIndex = currentIndex < triggers.length - 1 ? currentIndex + 1 : 0;
    }
    
    if (nextIndex !== undefined) {
      triggers[nextIndex].focus();
      triggers[nextIndex].click();
    }
  }
});